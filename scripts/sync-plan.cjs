// Keep direct-file previews working: a classic script avoids fetching local JSON.
const fs = require('node:fs');
const data = JSON.parse(fs.readFileSync('app/src/main/assets/ppl-plan.json', 'utf8'));
const output = '// Generated by scripts/sync-plan.cjs; edit app/src/main/assets/ppl-plan.json.\nconst PPL_PLAN = '+JSON.stringify(data,null,2)+';\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync('preview/plan.js','utf8') !== output) throw Error('Run node scripts/sync-plan.cjs');
} else fs.writeFileSync('preview/plan.js', output);
